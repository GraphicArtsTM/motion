"""Hand tracking → reels/hands.js.

Runs MediaPipe Hand Landmarker over the tone-mapped frames of the take and keeps,
for every frame, the palm of the raised hand: centre, size and fingertip height.
The track is gap-filled and lightly smoothed so the hologram sticks to the palm
and follows camera shake without detector jitter.

    python track_hands.py hand_landmarker.task frames/take hands.js
"""
import sys, glob, json, math
import numpy as np
import cv2
import mediapipe as mp
from mediapipe.tasks.python import vision, BaseOptions

model, frames_dir, out = sys.argv[1:4]
det = vision.HandLandmarker.create_from_options(vision.HandLandmarkerOptions(
    base_options=BaseOptions(model_asset_path=model), running_mode=vision.RunningMode.VIDEO,
    num_hands=2, min_hand_detection_confidence=0.3, min_tracking_confidence=0.3,
    min_hand_presence_confidence=0.3))

files = sorted(glob.glob(frames_dir + '/*.jpg'))
FPS = 60000 / 1001
raw = np.full((len(files), 4), np.nan)        # cx, cy, size, fingertip y
for i, f in enumerate(files):
    img = cv2.cvtColor(cv2.imread(f), cv2.COLOR_BGR2RGB)
    h, w = img.shape[:2]
    r = det.detect_for_video(mp.Image(image_format=mp.ImageFormat.SRGB, data=img), int(i * 1000 / FPS))
    best = None
    for lm in r.hand_landmarks:
        p = [(q.x * w, q.y * h) for q in lm]
        cx = sum(p[k][0] for k in (0, 5, 9, 13, 17)) / 5
        cy = sum(p[k][1] for k in (0, 5, 9, 13, 17)) / 5
        tip = min(p[k][1] for k in (8, 12, 16))
        size = math.dist(p[0], p[9])
        if best is None or tip < best[3]:   # the raised hand is the one reaching highest
            best = (cx, cy, size, tip)
    if best: raw[i] = best

# gaps → linear interpolation, then a short gaussian to remove detector jitter
idx = np.arange(len(raw))
for c in range(4):
    ok = ~np.isnan(raw[:, c])
    raw[:, c] = np.interp(idx, idx[ok], raw[ok, c])
k = np.exp(-0.5 * (np.arange(-6, 7) / 2.5) ** 2); k /= k.sum()
sm = np.stack([np.convolve(np.pad(raw[:, c], 6, mode='edge'), k, mode='valid') for c in range(4)], 1)

with open(out, 'w') as fh:
    fh.write('// generated by track_hands.py: per take frame [palmX, palmY, handSize, fingertipY], 1080×1920\n')
    fh.write('window.HANDS = ' + json.dumps([[round(float(v), 1) for v in row] for row in sm], separators=(',', ':')) + ';\n')
print(out, len(sm), 'frames')
